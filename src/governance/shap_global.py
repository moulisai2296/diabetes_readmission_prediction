"""Global feature importance via SHAP (XGBoost contributions).

The API already returns per-patient SHAP factors; this aggregates the *same*
`pred_contribs` (TreeSHAP) over a test sample to answer "what drives the model
overall?" — mean |SHAP| per feature, averaged across the calibration folds, exactly
the explainer used at serving (one source of truth for explanations).

Run:
  uv run python -m src.governance.shap_global

Writes:
  governance/shap_global_importance.md    ranked table
  governance/shap_global_importance.png    top-20 bar chart
"""

from __future__ import annotations

import logging
from pathlib import Path

import joblib
import matplotlib
import numpy as np
import pandas as pd
import xgboost as xgb

from src.api.featurize import load_spec

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

log = logging.getLogger("shap_global")

ROOT = Path(__file__).resolve().parents[2]
ARTIFACTS = ROOT / "artifacts"
OUT = ROOT / "governance"
SAMPLE = 2000


def _boosters(model) -> list:
    out = []
    for cc in getattr(model, "calibrated_classifiers_", []):
        est = getattr(cc, "estimator", None) or getattr(cc, "base_estimator", None)
        if est is not None:
            out.append(est.get_booster())
    return out


def global_importance(model, X: pd.DataFrame) -> pd.Series:
    """Mean |SHAP contribution| per feature, averaged across calibration folds."""
    boosters = _boosters(model)
    dm = xgb.DMatrix(X, enable_categorical=True)
    contribs = np.mean([b.predict(dm, pred_contribs=True) for b in boosters], axis=0)
    contribs = contribs[:, :-1]  # drop the bias column
    mean_abs = np.abs(contribs).mean(axis=0)
    return pd.Series(mean_abs, index=X.columns).sort_values(ascending=False)


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(name)s: %(message)s")
    spec = load_spec(ARTIFACTS / "feature_spec.json")
    model = joblib.load(ARTIFACTS / "model.joblib")
    test = pd.read_parquet(ROOT / "data_folder/processed/splits/test.parquet")

    X = test[spec["feature_order"]]
    if len(X) > SAMPLE:
        X = X.sample(SAMPLE, random_state=42)
    importance = global_importance(model, X)

    OUT.mkdir(exist_ok=True)
    lines = [
        "# Global Feature Importance (SHAP)",
        "",
        f"Mean |SHAP contribution| over {len(X):,} test encounters, averaged across the "
        "calibration folds — the same `pred_contribs` explainer the API uses per patient. "
        "Generated by `src/governance/shap_global.py`.",
        "",
        "| rank | feature | mean \\|SHAP\\| |",
        "|---|---|---|",
    ]
    for i, (feat, val) in enumerate(importance.items(), 1):
        lines.append(f"| {i} | {feat} | {val:.4f} |")
    (OUT / "shap_global_importance.md").write_text("\n".join(lines), encoding="utf-8")

    top = importance.head(20)[::-1]
    plt.figure(figsize=(8, 7))
    plt.barh(top.index, top.values, color="#0b6b4f")
    plt.xlabel("mean |SHAP contribution| (log-odds)")
    plt.title("Top 20 features driving readmission risk")
    plt.tight_layout()
    plt.savefig(OUT / "shap_global_importance.png", dpi=120)
    plt.close()

    log.info("wrote shap_global_importance.md + .png; top 5: %s",
             ", ".join(importance.head(5).index))


if __name__ == "__main__":
    main()
